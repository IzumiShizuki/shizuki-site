import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.Statement;
import java.time.LocalDateTime;
import java.util.Objects;
import javax.sql.DataSource;
import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.session.Configuration;
import org.apache.ibatis.session.SqlSessionFactoryBuilder;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;
import org.flywaydb.core.Flyway;
import org.postgresql.ds.PGSimpleDataSource;
import io.github.shizuki.site.content.entity.LightAppTodoEntity;
import io.github.shizuki.site.content.mapper.LightAppTodoMapper;

/** Standalone acceptance probe for a disposable PostgreSQL cluster started by run.ps1. */
public class UpgradeProbe {
    static final String TABLE = "flyway_schema_history_pg";

    static void expect(Object actual, Object expected) {
        if (!Objects.equals(actual, expected)) {
            throw new AssertionError("Expected " + expected + ", observed " + actual);
        }
    }

    static Flyway flyway(DataSource db, Path migrations) {
        return Flyway.configure().dataSource(db).locations("filesystem:" + migrations)
            .table(TABLE).baselineOnMigrate(true).baselineVersion("0").validateOnMigrate(true).load();
    }

    static int scalar(Statement sql, String query) throws Exception {
        try (var rows = sql.executeQuery(query)) {
            if (!rows.next()) throw new AssertionError("No row for count");
            return rows.getInt(1);
        }
    }

    static void verifyOldMapper(DataSource db) throws Exception {
        Path actual = Path.of(LightAppTodoMapper.class.getProtectionDomain().getCodeSource().getLocation().toURI());
        expect(actual.getFileName().toString(), "legacy-classes");
        var cfg = new Configuration(new Environment("legacy", new JdbcTransactionFactory(), db));
        cfg.addMapper(LightAppTodoMapper.class);
        try (var session = new SqlSessionFactoryBuilder().build(cfg).openSession(true)) {
            var mapper = session.getMapper(LightAppTodoMapper.class);
            expect(mapper.selectMaxSortNumByUserId(7L), 17);
            var task = new LightAppTodoEntity();
            task.setUserId(7L);
            task.setTitle("old mapper on new schema");
            task.setSortNum(29);
            task.setDone(false);
            task.setShowOnCalendar(true);
            task.setReminderEnabled(true);
            task.setRecurringRuleId(33L);
            task.setRecurringInstanceAt(LocalDateTime.of(2020, 1, 1, 12, 30));
            expect(mapper.insertRecurringIfAbsent(task), 1);
            expect(mapper.insertRecurringIfAbsent(task), 0);
            expect(mapper.selectMaxSortNumByUserId(7L), 29);
            task.setId(71L);
            expect(mapper.updateVersioned(task, 0), 1);
            expect(mapper.updateVersioned(task, 0), 0);
            expect(mapper.deleteVersioned(8L, 71L, 1), 0);
        }
    }

    public static void main(String[] args) throws Exception {
        var db = new PGSimpleDataSource();
        db.setServerNames(new String[]{"127.0.0.1"});
        db.setPortNumbers(new int[]{Integer.parseInt(args[0])});
        db.setDatabaseName("postgres");
        db.setUser("todo_qa");
        db.setPassword(System.getenv("TODO_QA_TEMP_PASSWORD"));
        Path root = Path.of(args[1]), resources = Path.of(args[2]);
        Path old = Files.createDirectory(root.resolve("old")), upgrade = Files.createDirectory(root.resolve("upgrade"));
        Path ahead = Files.createDirectory(root.resolve("ahead"));
        // A synthetic V1106 represents just the required legacy columns and constraints.
        String legacy = """
            CREATE TABLE usr_account (id bigint primary key);
            CREATE TABLE ctn_la_todo (
              id bigint generated by default as identity primary key, user_id bigint, project_id bigint,
              recurring_rule_id bigint, title_text text, detail_text text, priority_code text, done_flag smallint,
              due_datetime timestamp, show_on_calendar_flag smallint, time_precision_code text, timing_mode_code text,
              range_start_datetime timestamp, reminder_enabled_flag smallint, start_remind_value int,
              start_remind_unit_code text, deadline_remind_value int, deadline_remind_unit_code text,
              recurring_instance_datetime timestamp, sort_num int, deleted_flag smallint, version_num int,
              update_time timestamp, unique(user_id, recurring_rule_id, recurring_instance_datetime));
            INSERT INTO usr_account VALUES (7),(8);
            INSERT INTO ctn_la_todo(id,user_id,title_text,sort_num,deleted_flag,version_num,reminder_enabled_flag)
                VALUES(71,7,'existing',17,0,0,1);
            """;
        for (Path dir : new Path[]{old, upgrade, ahead}) {
            Files.writeString(dir.resolve("V1106__synthetic_legacy.sql"), legacy);
        }
        for (String name : new String[]{"V1106.1__light_app_todo_dev_workflow.sql","V1106.2__mcp_account_token.sql"}) {
            Files.copy(resources.resolve(name), upgrade.resolve(name));
        }
        Files.writeString(ahead.resolve("V1107__synthetic_other_release.sql"), "SELECT 1;");
        var prior = flyway(db, old);
        var candidate = flyway(db, upgrade);
        expect(prior.migrate().migrationsExecuted, 1);
        expect(candidate.migrate().migrationsExecuted, 2);
        candidate.validate();
        expect(candidate.migrate().migrationsExecuted, 0);
        try (Connection c = db.getConnection(); Statement sql = c.createStatement()) {
            expect(scalar(sql, "select count(*) from " + TABLE + " where success and version in ('1106.1','1106.2')"), 2);
            expect(scalar(sql, "select count(*) from ctn_la_todo where title_text='existing' and reminder_enabled_flag=1"), 1);
            for (String table : new String[]{"ctn_la_todo_dev","ctn_la_todo_dev_event","usr_mcp_account_token"}) {
                expect(scalar(sql, "select count(*) from " + table), 0);
            }
            sql.execute("insert into ctn_la_todo_dev(todo_id,repository_ref,stage_code,status_code) values(71,'example/repo','DESIGN','BLOCKED')");
            sql.execute("insert into ctn_la_todo_dev_event(todo_id,request_id,request_hash,event_type,stage_code,status_code,source_code,summary_text,resulting_version_num) values(71,'fixture','fixture','PROGRESS','DESIGN','BLOCKED','MCP','[RUN_FAILED] fixture',1)");
            sql.execute("insert into usr_mcp_account_token(user_id,token_sha256) values(7,repeat('a',64))");
            // A legacy runtime ending at V1106 reopens the same upgraded database.
            prior.validate();
            expect(prior.migrate().migrationsExecuted, 0);
            verifyOldMapper(db);
            expect(scalar(sql, "select count(*) from ctn_la_todo where user_id=7 and reminder_enabled_flag=1 and title_text='old mapper on new schema'"), 2);
            expect(scalar(sql, "select count(*) from ctn_la_todo_dev_event where todo_id=71 and status_code='BLOCKED'"), 1);
            expect(scalar(sql, "select count(*) from usr_mcp_account_token where user_id=7"), 1);
            candidate.validate();
            expect(candidate.migrate().migrationsExecuted, 0);
            // A different rollback image which already knows V1107 is a separate compatibility case.
            var errors = flyway(db, ahead).validateWithResult().invalidMigrations;
            var missing = errors.stream().filter(e -> e.errorDetails.errorCode.toString().equals("APPLIED_VERSIONED_MIGRATION_NOT_RESOLVED"))
                .map(e -> e.version).sorted().toList();
            expect(missing, java.util.List.of("1106.1", "1106.2"));
            System.out.println("PASS PostgreSQL " + c.getMetaData().getDatabaseProductVersion()
                + " / Flyway upgrade 2, replay 0, legacy V1106 validate/migrate 0, archived mapper read/insert/dedupe/update/version/owner passed;"
                + " reminder/workflow/event/token retained, re-upgrade 0; V1107-visible rollback rejected both missing migrations");
        }
    }
}
