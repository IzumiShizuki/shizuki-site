CREATE TABLE IF NOT EXISTS MDA_AMBIENT_SOURCE_ASSET (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '在线环境音来源映射 ID',
    user_id BIGINT NOT NULL COMMENT '资产所属用户',
    provider_code VARCHAR(32) NOT NULL COMMENT '来源平台，如 freesound',
    source_sound_id VARCHAR(64) NOT NULL COMMENT '来源平台音频 ID',
    asset_id BIGINT NULL COMMENT '导入成功后的站内资产 ID',
    import_status VARCHAR(16) NOT NULL DEFAULT 'IMPORTING' COMMENT 'IMPORTING/READY',
    title_text VARCHAR(256) NOT NULL DEFAULT '' COMMENT '导入时标题快照',
    author_text VARCHAR(256) NOT NULL DEFAULT '' COMMENT '作者快照',
    license_code VARCHAR(32) NOT NULL DEFAULT '' COMMENT '许可证编码',
    license_name VARCHAR(128) NOT NULL DEFAULT '' COMMENT '许可证名称',
    source_page_url VARCHAR(1024) NOT NULL DEFAULT '' COMMENT '来源详情页',
    duration_value DOUBLE NOT NULL DEFAULT 0 COMMENT '时长（秒）',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_flag TINYINT(1) NOT NULL DEFAULT 0,
    version_num INT NOT NULL DEFAULT 0,
    CONSTRAINT PK_MDA_AMBIENT_SOURCE_ASSET PRIMARY KEY (id),
    CONSTRAINT AK_MDA_AMBIENT_SOURCE_ASSET_1 UNIQUE (user_id, provider_code, source_sound_id),
    CONSTRAINT AK_MDA_AMBIENT_SOURCE_ASSET_2 UNIQUE (asset_id),
    KEY IX_MDA_AMBIENT_SOURCE_ASSET_1 (user_id, import_status),
    CONSTRAINT FK_MDA_AMBIENT_SOURCE_ASSET_1 FOREIGN KEY (asset_id) REFERENCES MDA_ASSET(id)
) COMMENT='在线环境音来源与私有资产幂等映射';
