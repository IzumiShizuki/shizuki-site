"""Regenerate committed Unicode shards using the existing FontTools + Brotli.

Production/CI consumes the generated CSS and WOFF2 files, not this Python tool.
Every original cmap entry is served by one disjoint CSS range per family.
Rare binaries keep their stable glyph groups; CSS excludes promoted characters.
"""
from collections import Counter
from hashlib import sha256
from pathlib import Path
import json
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/assets/fonts/subsets'
COMMON_HAN = 1024
RARE_SIZE = 128
FAMILIES = [
    ('NotoSansSC-subset.woff2', 'noto', 'Noto Sans SC', '300 800'),
    ('LXGWWenKai.woff2', 'wenkai', 'LXGW WenKai Screen', '400 700'),
]

def ranges(points):
    values = sorted(points)
    result = []
    start = end = values[0]
    for point in values[1:]:
        if point == end + 1:
            end = point
        else:
            result.append(f'U+{start:X}' + (f'-{end:X}' if start != end else ''))
            start = end = point
    result.append(f'U+{start:X}' + (f'-{end:X}' if start != end else ''))
    return ','.join(result)

def parse_ranges(value):
    result = set()
    for part in value.split(','):
        limits = part.removeprefix('U+').split('-')
        start, end = int(limits[0], 16), int(limits[-1], 16)
        result.update(range(start, end + 1))
    return result

frequency = Counter()
for path in sorted((ROOT / 'src').rglob('*')):
    if path.suffix in {'.vue', '.js', '.ts'} and '.spec.' not in path.name:
        frequency.update(ord(c) for c in path.read_text(encoding='utf-8') if ord(c) >= 0x3400)
common = {point for point, _ in frequency.most_common(COMMON_HAN)}
priority_file = ROOT / 'scripts/font-priority.json'
priority = json.loads(priority_file.read_text(encoding='utf-8'))['families'] if priority_file.exists() else {}
old_path = OUTPUT / 'manifest.json'
previous = json.loads(old_path.read_text(encoding='utf-8')) if old_path.exists() else {'families': []}
OUTPUT.mkdir(parents=True, exist_ok=True)
css = ['/* Generated by scripts/build-font-subsets.py; preserve family and full cmap coverage. */']
manifest = {'commonHanCount': COMMON_HAN, 'rareShardSize': RARE_SIZE, 'families': []}
for source_name, slug, family, weight in FAMILIES:
    source = ROOT / 'public/fonts' / source_name
    original = TTFont(source, recalcTimestamp=False)
    expected = set(original.getBestCmap())
    settings = priority.get(slug)
    base = parse_ranges(settings['baseRange']) if settings else {p for p in expected if p < 0x3400} | (common & expected)
    first = base | (set(settings['priorityCodepoints']) & expected if settings else set())
    rest = sorted(expected - base)
    groups = [first] + [set(rest[i:i + RARE_SIZE]) for i in range(0, len(rest), RARE_SIZE)]
    old_family = next((f for f in previous['families'] if f['family'] == family), {})
    old_files = {s['file']: s for s in old_family.get('shards', [])}
    record = {'family': family, 'source': source_name, 'sourceSha256': sha256(source.read_bytes()).hexdigest(),
              'coverage': ranges(expected), 'shards': []}
    actual = set()
    for index, points in enumerate(groups):
        served = set(points) if index == 0 else set(points) - first
        if not served:
            unused = OUTPUT / f'{slug}-{index:02d}.woff2'
            assert unused.resolve().parent == OUTPUT.resolve()
            unused.unlink(missing_ok=True)
            continue
        path = OUTPUT / f'{slug}-{index:02d}.woff2'
        old_file = old_files.get(path.name, {})
        reusable = path.exists() and old_family.get('sourceSha256') == record['sourceSha256'] and old_file.get('sha256') == sha256(path.read_bytes()).hexdigest()
        if not reusable or set(TTFont(path).getBestCmap()) != set(points):
            font = TTFont(source, recalcTimestamp=False)
            options = subset.Options()
            options.name_IDs = ['*']
            options.name_legacy = True
            options.recalc_timestamp = False
            worker = subset.Subsetter(options=options)
            worker.populate(unicodes=points)
            worker.subset(font)
            font.flavor = 'woff2'
            font.save(path)
        saved = set(TTFont(path).getBestCmap())
        assert saved == set(points) and served <= saved and not (actual & served), path.name
        actual.update(served)
        unicode_range = ranges(served)
        payload = path.read_bytes()
        record['shards'].append({'file': path.name, 'unicodeRange': unicode_range,
                                 'bytes': len(payload), 'sha256': sha256(payload).hexdigest()})
        css.append(f"@font-face{{font-family:'{family}';src:url('../assets/fonts/subsets/{path.name}') format('woff2');"
                   f'font-weight:{weight};font-style:normal;font-display:swap;unicode-range:{unicode_range};}}')
    assert actual == expected, family
    manifest['families'].append(record)
    print(f'{family}: {len(expected)} codepoints, {len(groups)} shards, common {record["shards"][0]["bytes"]} bytes', flush=True)
(OUTPUT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
(ROOT / 'src/styles/font-subsets.css').write_text('\n'.join(css) + '\n', encoding='utf-8', newline='\n')
